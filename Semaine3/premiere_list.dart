void main() {
  // Créer une liste
  List<String> fruits = ['Pomme', 'Banane', 'Orange'];
  
  // Afficher la liste
  print('Liste de fruits:');
  print(fruits);
  
  // Accéder à un élément (index commence à 0)
  print('Premier fruit: ${fruits[0]}');
  print('Deuxième fruit: ${fruits[1]}');
  
  // Nombre d'éléments
  print('Nombre de fruits: ${fruits.length}');
}